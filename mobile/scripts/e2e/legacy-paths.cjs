// Table of the website's former French addresses (feature 018), handed to the Maestro scripts.
const { readFileSync } = require("node:fs");
const path = require("node:path");

/** `src/site/legacy-paths.json` of the repository. */
function readLegacyPaths(repoRoot) {
  return JSON.parse(readFileSync(path.join(repoRoot, "src/site/legacy-paths.json"), "utf8"));
}

/** Maestro script that puts the table in `output.legacyPaths`, for `scripts/former-link.js`. */
function renderLegacyPathsScript(table) {
  return `// Generated by scripts/e2e.mjs from src/site/legacy-paths.json, do not edit or commit.\noutput.legacyPaths = ${JSON.stringify(table)};\n`;
}

module.exports = { readLegacyPaths, renderLegacyPathsScript };
